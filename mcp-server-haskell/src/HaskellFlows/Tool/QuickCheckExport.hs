-- | The leading comment we stamp on every generated file.  Used as
-- a sentinel to tell apart a previously-generated file (safe to
-- overwrite) from a hand-written one (needs 'eaForce').
--
-- Issue #198: updated to the current tool name (@ghc_property_store@).
-- The old @ghc_quickcheck_export@ name was retired in #94 Phase C.
generatedHeader :: Text
generatedHeader = "-- Generated by ghc_property_store."

-- | Header produced by 'HaskellFlows.Tool.CreateProject.testFile' —
-- the scaffold stub written by @ghc_project(action=\"create\")@.
-- Also safe to overwrite with a property-store export (both are
-- MCP-generated; the stub is intentionally replaced by a real suite).
scaffoldTestFileHeader :: Text
scaffoldTestFileHeader = "-- | Scaffolded test suite."

data ExportArgs = ExportArgs
  { eaOutputPath :: !(Maybe Text)
  , eaModule     :: !(Maybe Text)
  -- | #131: bypass the hand-written-file guard.  When 'False'
  -- (default) the export refuses to overwrite a file that does not
  -- start with 'generatedHeader'.  Set to 'True' to proceed anyway.
  , eaForce      :: !Bool
  }
  deriving stock (Show)

instance FromJSON ExportArgs where
  parseJSON = withObject "ExportArgs" $ \o ->
    ExportArgs
      <$> o .:? "output_path"
      <*> o .:? "module"
      <*> (fromMaybe False <$> o .:? "force")

