handle :: Store -> ProjectDir -> Value -> IO ToolResponse
handle store pd rawArgs = case parseEither parseJSON rawArgs of
  Left err -> pure (formatParseError err)
  Right args -> do
    props <- loadAll store
    let filtered = case eaModule args of
          Nothing -> props
          Just m  -> [ p | p <- props, spModule p == Just m ]
        outRel = maybe "test/Spec.hs" T.unpack (eaOutputPath args)
    case mkModulePath pd outRel of
      Left err -> pure (pathTraversalResult
                          (T.pack ("Invalid output path: " <> show err)))
      Right mp -> do
        -- Resolve the project's library exposed-modules so a property
        -- whose 'spModule' was a test scope (e.g. 'test/Spec.hs') can
        -- still reference library symbols (issue #40). 'libraryExposedModules'
        -- returns @[]@ on any I/O / parse failure so a corrupt or
        -- absent .cabal degrades to the historical behaviour.
        libMods <- Qc.libraryExposedModules pd
        -- Identify the would-be module name for the output file. Any
        -- inferred import that matches it is the file importing
        -- itself — circular and invalid (#40).
        let selfHint = modulePathToModule (T.pack outRel)
            full     = unModulePath mp
            body     = renderTestFileWith selfHint libMods filtered
        -- #131: guard against silently overwriting a hand-written file.
        -- Only bypass when the caller passes force=true or the file
        -- starts with our generated header (safe to regenerate).
        guardResult <- exportGuard full (eaForce args)
        case guardResult of
          Just refusal -> pure refusal
          Nothing -> do
            eRes <- try (do
              createDirectoryIfMissing True (takeDirectory full)
              TIO.writeFile full body) :: IO (Either SomeException ())
            case eRes of
              Left ex -> pure (subprocessResult
                                  (T.pack ("Could not write: " <> show ex)))
              Right _ -> pure (successResult full (length filtered) (length props))
  where
    _ = unProjectDir pd  -- silence unused when path validation is the only use

-- | #131: Check whether writing to 'path' is safe.
--
--   * File does not exist → 'Nothing' (proceed).
--   * File exists + starts with 'generatedHeader' → 'Nothing' (safe to
--     regenerate — the MCP wrote it last time).
--   * File exists + 'force' is 'True' → 'Nothing' (caller opted in).
--   * File exists + no generated header + no force → 'Just' a refusal
--     result so the caller can stop.
--
-- This prevents the critical data-loss scenario where
-- @ghc_property_store(action=\"export\")@ silently overwrites a
-- hand-crafted test suite (issue #131).
exportGuard :: FilePath -> Bool -> IO (Maybe ToolResponse)
exportGuard path force = do
  exists <- doesFileExist path
  if not exists || force
    then pure Nothing
    else do
        eFirst <- try (TIO.readFile path) :: IO (Either SomeException Text)
        case eFirst of
          Left _      -> pure Nothing  -- unreadable → let writeFile handle it
          Right content ->
            if generatedHeader       `T.isPrefixOf` content
               || scaffoldTestFileHeader `T.isPrefixOf` content
              then pure Nothing  -- MCP-generated → safe to overwrite
              else pure (Just (handWrittenGuardResult path))

